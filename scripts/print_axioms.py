#!/usr/bin/env python3
"""Audit the axioms of every constant defined in the `Peluang` library.

Requires an up-to-date build of the `Peluang` target (checked with
`lake build --no-build Peluang`).
Elaborates a probe that imports `Peluang` and, for every constant of a
`Peluang` / `Peluang.*` module (theorems, definitions, instances, private and
auxiliary declarations alike), prints the axioms `Lean.collectAxioms` reports
and its declaration ranges. Every `lake` call runs with lean/ as the working
directory, so elan selects the toolchain in lean/lean-toolchain. Exit 0 when
the build is current, the probe elaborates, every constant depends only on
axioms in ALLOWED, every library file is among the loaded modules, and the
theorems check_theorem_map scans equal the library's source theorems; exit 1
otherwise, printing each failure on its own line. A source theorem is a
non-internal theorem constant whose declaration range holds a `theorem` /
`lemma` keyword and whose selection range is the constant's own name, which
excludes lemmas generated by attributes, Prop-valued instances and aliases.

Usage: print_axioms.py [REPO_ROOT]
"""

from __future__ import annotations

import re
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_theorem_map as ctm  # noqa: E402
from check_lean_source import strip_code  # noqa: E402

ALLOWED = frozenset({"propext", "Classical.choice", "Quot.sound"})
TIMEOUT_S = 900
PRIVATE_PREFIX = "_private."
KEYWORD_RE = re.compile(r"(?<![\w.'])(?:theorem|lemma)(?![\w'])")

PROBE = """import Lean.Util.CollectAxioms
import Lean.DeclarationRange
import Peluang

open Lean Elab Command in
run_cmd do
  let env ← getEnv
  let mods := env.header.moduleNames
  for i in [:mods.size] do
    let m := mods[i]!
    if (`Peluang).isPrefixOf m then
      IO.println s!"MODULE\\t{m}"
      for n in env.header.moduleData[i]!.constNames do
        let some ci := env.find? n | continue
        let axs ← liftCoreM (Lean.collectAxioms n)
        let r ← liftCoreM (findDeclarationRanges? n)
        let thm := (ci matches .thmInfo _) && !(privateToUserName n).isInternalDetail
        let pos := match r with
          | some r => s!"{r.range.pos.line}:{r.range.pos.column}:{r.selectionRange.pos.line}:{r.selectionRange.pos.column}:{r.selectionRange.endPos.line}:{r.selectionRange.endPos.column}"
          | none => "-"
        IO.println s!"CONST\\t{n}\\t{m}\\t{thm}\\t{pos}\\t{String.intercalate "," (axs.toList.map toString)}"
"""


@dataclass(frozen=True)
class Const:
    name: str
    module: str
    theorem: bool
    ranges: tuple[int, int, int, int, int, int] | None
    axioms: tuple[str, ...]


@dataclass
class ProbeResult:
    modules: set[str] = field(default_factory=set)
    consts: list[Const] = field(default_factory=list)


def display_name(name: str) -> str:
    if name.startswith(PRIVATE_PREFIX) and ".0." in name:
        name = name.split(".0.", 1)[1]
    return name.replace("«", "").replace("»", "")


def parse_output(output: str) -> ProbeResult:
    result = ProbeResult()
    for line in output.splitlines():
        parts = line.split("\t")
        if parts[0] == "MODULE" and len(parts) == 2:
            result.modules.add(parts[1])
        elif parts[0] == "CONST" and len(parts) == 6:
            nums = parts[4].split(":")
            ranges = tuple(int(x) for x in nums) if len(nums) == 6 and all(x.isdigit() for x in nums) else None
            result.consts.append(
                Const(parts[1], parts[2], parts[3] == "true", ranges, tuple(a for a in parts[5].split(",") if a))
            )
    return result


def module_file(lean_dir: Path, module: str) -> Path:
    return lean_dir.joinpath(*module.split(".")).with_suffix(".lean")


def module_names(lean_dir: Path) -> list[str]:
    return [".".join(p.relative_to(lean_dir).with_suffix("").parts) for p in ctm.library_files(lean_dir)]


def text_between(lines: list[str], l1: int, c1: int, l2: int, c2: int) -> str:
    if not (1 <= l1 <= l2 <= len(lines)):
        return ""
    if l1 == l2:
        return lines[l1 - 1][c1:c2]
    return "\n".join([lines[l1 - 1][c1:], *lines[l1 : l2 - 1], lines[l2 - 1][:c2]])


def is_source_theorem(c: Const, lines: list[str]) -> bool:
    if not c.theorem or c.ranges is None:
        return False
    rl, rc, sl, sc, el, ec = c.ranges
    header = strip_code(text_between(lines, rl, rc, sl, sc))
    written = text_between(lines, sl, sc, el, ec).replace("«", "").replace("»", "").removeprefix("_root_.")
    name = display_name(c.name)
    return bool(KEYWORD_RE.search(header)) and bool(written) and (name == written or name.endswith("." + written))


def source_theorems(result: ProbeResult, read_lines) -> set[str]:
    cache: dict[str, list[str]] = {}
    out: set[str] = set()
    for c in result.consts:
        if c.module not in cache:
            cache[c.module] = read_lines(c.module)
        if is_source_theorem(c, cache[c.module]):
            out.add(display_name(c.name))
    return out


def evaluate(result: ProbeResult, on_disk: list[str], scanned: list[str], sources: set[str]) -> list[str]:
    failures: list[str] = []
    for m in on_disk:
        if m not in result.modules:
            failures.append(f"`{m}`: library file is not imported (transitively) by lean/Peluang.lean")
    for c in sorted(result.consts, key=lambda c: c.name):
        bad = sorted(a for a in c.axioms if a not in ALLOWED)
        if bad:
            failures.append(
                f"`{display_name(c.name)}`: depends on {', '.join(bad)} (allowed: {', '.join(sorted(ALLOWED))})"
            )
    scanned_set = {display_name(n) for n in scanned}
    for n in sorted(scanned_set - sources):
        failures.append(f"`{n}`: scanned as a theorem by check_theorem_map but is not a source theorem of the library")
    for n in sorted(sources - scanned_set):
        failures.append(f"`{n}`: source theorem of the library that check_theorem_map does not scan")
    return failures


def run_lake(args: list[str], lean_dir: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["lake", *args], cwd=lean_dir, capture_output=True, text=True, check=False, timeout=TIMEOUT_S
    )


def check(root: Path) -> tuple[int, list[str]]:
    lean_dir = root / "lean"
    scanned = [d.qualified for d in ctm.library_decls(lean_dir)]
    try:
        fresh = run_lake(["build", "--no-build", "Peluang"], lean_dir)
        if fresh.returncode != 0:
            return 0, [f"lean build is stale or missing; run `env -C lean lake build Peluang`:\n{(fresh.stdout + fresh.stderr).rstrip()}"]
        with tempfile.TemporaryDirectory() as tmp:
            probe = Path(tmp) / "Probe.lean"
            probe.write_text(PROBE, encoding="utf-8")
            proc = run_lake(["env", "lean", str(probe)], lean_dir)
    except (OSError, subprocess.TimeoutExpired) as e:
        return 0, [f"could not run `lake` in {lean_dir}: {e}"]
    output = proc.stdout + proc.stderr
    if proc.returncode != 0:
        return 0, [f"lean exited {proc.returncode}:\n{output.rstrip()}"]
    result = parse_output(output)

    def read_lines(module: str) -> list[str]:
        path = module_file(lean_dir, module)
        return path.read_text(encoding="utf-8").splitlines() if path.is_file() else []

    sources = source_theorems(result, read_lines)
    return len(result.consts), evaluate(result, module_names(lean_dir), scanned, sources)


def main(argv: list[str]) -> int:
    root = Path(argv[1]).resolve() if len(argv) > 1 else Path(__file__).resolve().parent.parent
    count, failures = check(root)
    for f in failures:
        print(f)
    if failures:
        print(f"print_axioms: {len(failures)} failure(s) over {count} constant(s)")
        return 1
    print(f"print_axioms: ok ({count} constant(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
